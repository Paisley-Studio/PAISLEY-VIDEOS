// Writes docs/STORYBOARD.md from narration/video-XX/script.json + timings.json:
// every scene's measured timing, visuals, camera, on-screen text, sound,
// music, transition and exact narration. Re-run after editing any script.
// Usage: node scripts/build-storyboard.ts

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createTimeline, FPS, type VideoScript } from "../src/lib/timeline.ts";

const ROOT = join(import.meta.dirname, "..");
const t = (frames: number) => {
  const s = frames / FPS;
  return `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;
};

let md = "# Number Match: six-video storyboard and narration\n\n";
md += "_Generated by `node scripts/build-storyboard.ts` from `narration/video-XX/script.json` and the measured voice timings. Do not edit by hand._\n\n";
const summary: string[] = ["| # | Composition | Title | Duration | Scenes | Narration lines | Output file |", "|---|---|---|---|---|---|---|"];
let body = "";

for (const video of ["01", "02", "03", "04", "05", "06"]) {
  const folder = join(ROOT, "narration", `video-${video}`);
  const script = JSON.parse(readFileSync(join(folder, "script.json"), "utf8")) as VideoScript;
  const timingsPath = join(folder, "timings.json");
  const timings = existsSync(timingsPath) ? JSON.parse(readFileSync(timingsPath, "utf8")) : null;
  const tl = timings ? createTimeline(script, timings) : null;
  const lines = script.scenes.reduce((a, s) => a + s.lines.length, 0);
  summary.push(`| ${video} | \`${script.compositionId}\` | ${script.title} | ${tl ? t(tl.TOTAL_FRAMES) : "n/a"} | ${script.scenes.length} | ${lines} | \`${script.output}.mp4\` |`);

  body += `\n---\n\n## Video ${Number(video)}: ${script.title}\n### "${script.subtitle}"\n\n`;
  body += `Composition \`${script.compositionId}\` · voice \`${script.voice}\` at ${script.rate} · ${tl ? `total ${t(tl.TOTAL_FRAMES)}` : "timings not generated"}\n\n`;
  script.scenes.forEach((scene, n) => {
    const st = tl?.getScene(scene.id);
    body += `### ${Number(video)}.${n + 1} ${scene.name}  \`${st ? `${t(st.from)} to ${t(st.from + st.durationInFrames)} (${(st.durationInFrames / FPS).toFixed(1)} s)` : ""}\`\n\n`;
    const field = (k: string, label: string) => {
      if (scene[k]) body += `- **${label}:** ${String(scene[k])}\n`;
    };
    field("visual", "Visual");
    field("camera", "Camera");
    field("onScreen", "On-screen text");
    field("sfx", "Sound effects");
    field("music", "Music");
    field("transition", "Transition");
    if (scene.lines.length) {
      body += `- **Narration and subtitles:**\n`;
      for (const line of scene.lines) {
        const lt = st?.lines.find((l) => l.id === line.id);
        const at = lt && st ? ` _(${t(st.from + lt.start)})_` : "";
        body += `  - \`${line.id}\`${at} ${line.text}\n`;
        if (line.caption && line.caption !== line.text) body += `    - subtitle: ${line.caption}\n`;
      }
    } else {
      body += `- **Narration:** none (music and sound only)\n`;
    }
    body += "\n";
  });
}

md += summary.join("\n") + "\n" + body;
writeFileSync(join(ROOT, "docs", "STORYBOARD.md"), md, "utf8");
console.log("wrote docs/STORYBOARD.md");
console.log(summary.join("\n"));
